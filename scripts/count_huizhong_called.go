// count_huizhong_called: 统计惠众 10 月账单里的 486 个税号中，
// 有多少在 2026 年 10 月（北京时间）被我方「任一下游」调用过，有多少完全没被调用过。
// 只读线上库，直接在终端打印两个数字。
//
// 用法（已内置默认配置文件，直接运行即可）：
//
//	CONFIG_FILE=config.aliyun.prod.yaml go run ./scripts/count_huizhong_called.go
//
// 口径：
//   - 「调用过」= audit_log 里存在该税号(credit_code)且 created_at 落在 2026-10 北京自然月的记录；
//     audit_log 有记录即表示通过鉴权/参数校验并实际发起了查询（含查无、上游失败）。
//   - 不限 app_key / 客户，即「我方所有下游」。
//   - 该库(datahub_swfp_db)即 swfp 线路，无需再按线路过滤。
package main

import (
	"context"
	"encoding/csv"
	"fmt"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"gopkg.in/yaml.v3"
)

var cst = time.FixedZone("CST", 8*3600)

type dbConfig struct {
	Versions map[string]struct {
		Database struct {
			Host     string `yaml:"host"`
			Port     int    `yaml:"port"`
			Name     string `yaml:"name"`
			User     string `yaml:"user"`
			Password string `yaml:"password"`
			SSLMode  string `yaml:"sslmode"`
		} `yaml:"database"`
	} `yaml:"versions"`
}

func env(k, def string) string {
	if v := os.Getenv(k); v != "" {
		return v
	}
	return def
}

func fail(format string, a ...any) {
	fmt.Printf(format+"\n", a...)
	os.Exit(1)
}

func main() {
	configFile := env("CONFIG_FILE", "config.aliyun.prod.yaml")
	// 统计月份（北京时间自然月），默认 2026 年 10 月。
	month := env("MONTH", "2026-10")
	from, err := time.ParseInLocation("2006-01", month, cst)
	if err != nil {
		fail("MONTH 格式应为 YYYY-MM: %v", err)
	}
	to := from.AddDate(0, 1, 0)

	raw, err := os.ReadFile(configFile)
	if err != nil {
		fail("读取配置失败: %v", err)
	}
	var cfg dbConfig
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		fail("解析配置失败: %v", err)
	}
	db := cfg.Versions["swfp"].Database
	if db.Host == "" {
		fail("配置里没有 versions.swfp.database")
	}
	if db.Port == 0 {
		db.Port = 5432
	}
	if db.SSLMode == "" {
		db.SSLMode = "disable"
	}

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	conn, err := pgx.Connect(ctx, fmt.Sprintf("host=%s port=%d user=%s password=%s dbname=%s sslmode=%s connect_timeout=15",
		db.Host, db.Port, db.User, db.Password, db.Name, db.SSLMode))
	if err != nil {
		fail("连接失败: %v", err)
	}
	defer conn.Close(ctx)
	if _, err := conn.Exec(ctx, "SET default_transaction_read_only = on"); err != nil {
		fail("设置只读失败: %v", err)
	}

	// 账单税号去重
	seen := map[string]bool{}
	uniq := make([]string, 0, len(huizhongCodes))
	for _, c := range huizhongCodes {
		if !seen[c] {
			seen[c] = true
			uniq = append(uniq, c)
		}
	}

	var called int
	err = conn.QueryRow(ctx, `
SELECT COUNT(DISTINCT credit_code)
FROM audit_log
WHERE credit_code = ANY($1)
  AND created_at >= $2 AND created_at < $3`, uniq, from, to).Scan(&called)
	if err != nil {
		fail("查询失败: %v", err)
	}

	total := len(uniq)
	notCalled := total - called
	fmt.Printf("惠众10月账单税号总数(去重): %d\n", total)
	fmt.Printf("统计月份(北京时间): %s ~ %s\n", from.Format("2006-01-02"), to.Format("2006-01-02"))
	fmt.Printf("其中10月被我方任一下游调用过的税号数: %d\n", called)
	fmt.Printf("其中10月完全未被我方任一下游调用过的税号数: %d\n", notCalled)

	// 逐条明细：每个税号被哪些下游调用（及各自次数）。
	type caller struct {
		name string
		cnt  int
	}
	detail := map[string][]caller{}
	rows, err := conn.Query(ctx, `
SELECT a.credit_code, COALESCE(NULLIF(l.name,''), a.app_key) AS downstream, COUNT(*)
FROM audit_log a
LEFT JOIN license l ON l.app_key = a.app_key
WHERE a.credit_code = ANY($1)
  AND a.created_at >= $2 AND a.created_at < $3
GROUP BY a.credit_code, downstream
ORDER BY a.credit_code, downstream`, uniq, from, to)
	if err != nil {
		fail("查询明细失败: %v", err)
	}
	for rows.Next() {
		var code, name string
		var cnt int
		if err := rows.Scan(&code, &name, &cnt); err != nil {
			fail("读取明细失败: %v", err)
		}
		detail[code] = append(detail[code], caller{name, cnt})
	}
	if err := rows.Err(); err != nil {
		fail("读取明细失败: %v", err)
	}

	sorted := append([]string(nil), uniq...)
	sort.Strings(sorted)

	outCSV := env("OUT", fmt.Sprintf("huizhong_callers_%s.csv", month))
	f, err := os.Create(outCSV)
	if err != nil {
		fail("创建CSV失败: %v", err)
	}
	defer f.Close()
	f.WriteString("\xEF\xBB\xBF") // UTF-8 BOM，便于 Excel 打开
	w := csv.NewWriter(f)
	w.Write([]string{"税号", "是否被调用", "下游数", "下游明细(名称:次数)"})

	fmt.Printf("\n=== 每个税号的下游调用情况 (%s) ===\n", month)
	for _, code := range sorted {
		cs := detail[code]
		if len(cs) == 0 {
			fmt.Printf("%s  (无下游调用)\n", code)
			w.Write([]string{code, "否", "0", ""})
			continue
		}
		parts := make([]string, 0, len(cs))
		for _, c := range cs {
			parts = append(parts, fmt.Sprintf("%s(%d)", c.name, c.cnt))
		}
		joined := strings.Join(parts, "; ")
		fmt.Printf("%s  调用下游: %s\n", code, joined)
		w.Write([]string{code, "是", fmt.Sprintf("%d", len(cs)), joined})
	}
	w.Flush()
	if err := w.Error(); err != nil {
		fail("写CSV失败: %v", err)
	}
	fmt.Printf("\n明细已导出: %s\n", outCSV)
}

